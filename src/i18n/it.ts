/** Grammatical gender for Italian piece names (torre, donna are feminine). */
const FEMININE = new Set(['torre', 'donna', 'regina']);
const isFem = (piece: string) => FEMININE.has(piece);
const nessun = (piece: string) => (isFem(piece) ? `Nessuna ${piece}` : `Nessun ${piece}`);
const quel = (piece: string) =>
  isFem(piece) ? `quella ${piece}` : /^[aeiou]/.test(piece) ? `quell'${piece}` : `quel ${piece}`;
const withArticle = (piece: string) =>
  isFem(piece) ? `la ${piece}` : /^[aeiou]/.test(piece) ? `l'${piece}` : `il ${piece}`;

